package Modulo_4;

public class BucleFor {
    public static void main(String[] args) {
        // Bucle For - Permite ejecutar un bloque de código un número determinado de veces

        // Ejemplo de bucle for
        for (int i = 0; i < 5; i++) {
            System.out.println("Contador: " + i);
        }

        // Ejemplo de bucle for con decremento
        for (int j = 5; j > 0; j--) {
            System.out.println("Contador decreciente: " + j);
        }

        // Ejemplo de bucle for con incremento de 2 en 2
        for (int k = 0; k < 10; k += 2) {
            System.out.println("Contador incrementando de 2 en 2: " + k);
        }
    }
}
