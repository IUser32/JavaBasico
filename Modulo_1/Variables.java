package Modulo_1;
public class Variables {
    public static void main(String[] args) {
        // Variables - Primarias

        // int => Integer | Para numeros enteros (SIN PARTE DECIMAL).
        int valor_1 = 78;

        // double => Double | Para numeros con parte decimal.
        double valor_2 = 78.4;

        // char => Character | Para caracteres.
        char valor_3 = '+';

        // boolean => Boolean | Para valores de verdadero (1) o falso (0).
        boolean valor_4 = true;

        // String => Cadena de texto | Para cadenas de texto.
        String mensaje = "Hola Mundo!";

        System.out.println("Valor 1: " + valor_1);
        System.out.println("Valor 2: " + valor_2);
        System.out.println("Valor 3: " + valor_3);
        System.out.println("Valor 4: " + valor_4);
        System.out.println("Mensaje: " + mensaje);
    }
}