package Modulo_1;
public class Constantes {
    public static void main(String[] args) {
        // Constantes - Valores que no cambian durante la ejecución del programa

        // Declaración de una constante de tipo int
        final int CONSTANTE_ENTERA = 100;

        // CONSTANTE_ENTERA = 80; // No se puede modificar el valor de una constante
        
        // Declaración de una constante de tipo double
        final double CONSTANTE_DECIMAL = 3.14;

        // Declaración de una constante de tipo char
        final char CONSTANTE_CARACTER = 'C';

        // Declaración de una constante de tipo boolean
        final boolean CONSTANTE_BOOLEANA = true;

        // Declaración de una constante de tipo String
        final String CONSTANTE_TEXTO = "Constante de texto";

        System.out.println("Constante Entera: " + CONSTANTE_ENTERA);
        System.out.println("Constante Decimal: " + CONSTANTE_DECIMAL);
        System.out.println("Constante Caracter: " + CONSTANTE_CARACTER);
        System.out.println("Constante Booleana: " + CONSTANTE_BOOLEANA);
        System.out.println("Constante Texto: " + CONSTANTE_TEXTO);
    }
}
